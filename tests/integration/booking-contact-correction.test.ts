import test from "node:test";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { createRequire } from "node:module";
import { build } from "esbuild";
import { db } from "../../src/lib/db";
import { verificationHash, emailVerificationHash, verifyPublicReservation, verifyPublicReservationEmail } from "../../src/lib/public-booking-service";
import { normalizeTwilioRecipient } from "../../src/lib/integrations/twilio-provider";
type Row = Record<string, any>; // eslint-disable-line @typescript-eslint/no-explicit-any

test("isolated PostgreSQL contact correction preserves holds, invalidates codes and protects other bookings", async t => {
  assert.equal(process.env.MERCHANDISE_DB_TEST, "isolated-ci");
  const url = new URL(process.env.DATABASE_URL!);
  assert.equal(url.hostname, "localhost"); assert.match(url.pathname, /_ci$/);
  t.mock.method(globalThis, "fetch", () => { throw Error("External transport forbidden"); });
  process.env.PUBLIC_RESERVATION_VERIFICATION_ENABLED = "true";
  process.env.PUBLIC_BOOKING_API_KEY = "isolated-fixture-only";
  const key = randomUUID();
  const org = await db.organisation.create({ data: { name: "Correction CI", slug: key } });
  const facility = await db.facility.create({ data: { organisationId: org.id, name: "CI", code: key } });
  const type = await db.unitType.create({ data: { facilityId: facility.id, name: "CI" } });
  const unit = await db.unit.create({ data: { facilityId: facility.id, unitTypeId: type.id, number: "CI", monthlyRate: 100, status: "RESERVED" } });
  const customer = await db.customer.create({ data: { organisationId: org.id, firstName: "Fixture", email: "typo@example.invalid", phone: "+27810000000" } });
  const hold = new Date(Date.now() + 8 * 60 * 1000);
  const reservation = await db.reservation.create({ data: { facilityId: facility.id, unitId: unit.id, customerId: customer.id, publicReference: key, idempotencyKey: key, source: "PUBLIC_WEBSITE", quotedRate: 100, journey: "RENTAL", holdExpiresAt: hold, verificationExpiresAt: hold } });
  await db.reservation.update({ where: { id: reservation.id }, data: { verificationCodeHash: verificationHash(reservation.id, "111111") } });
  const sends: Row[] = [];
  let delivered = true;
  const state = { db, normalizeTwilioRecipient, verificationHash, emailVerificationHash, deliverVerificationCode: async (input: Row) => { sends.push(input); return delivered ? { ok: true, channel: "WHATSAPP" } : { ok: false }; }, deliverEmailVerificationCode: async (input: Row) => { sends.push(input); return { ok: delivered }; } };
  const output = await build({ entryPoints: ["src/lib/public-booking-contact.ts"], bundle: true, write: false, platform: "node", format: "cjs", packages: "external", plugins: [{ name: "isolated-transport", setup(builder) {
    builder.onResolve({ filter: /^@\/lib\/(db|public-booking-service|integrations\/twilio-provider)$/ }, args => ({ path: args.path, namespace: "fixture" }));
    builder.onLoad({ filter: /.*/, namespace: "fixture" }, args => ({ contents: args.path.endsWith("/db") ? "export const db=__state.db;" : args.path.endsWith("/twilio-provider") ? "export const normalizeTwilioRecipient=__state.normalizeTwilioRecipient;" : "export const {verificationHash,emailVerificationHash,deliverVerificationCode,deliverEmailVerificationCode}=__state;" }));
  } }] });
  const loaded = { exports: {} as Row };
  new Function("require", "module", "exports", "__state", output.outputFiles[0].text)(createRequire(import.meta.url), loaded, loaded.exports, state);
  const correct = (channel = "MOBILE", value = "082 000 0000", bookingKey = key) => loaded.exports.correctPublicBookingContact(loaded.exports.contactCorrectionSchema.parse({ reference: key, bookingKey, channel, value }));
  try {
    assert.equal((await correct("MOBILE", "0820000000", randomUUID())).ok, false);
    assert.equal(sends.length, 0);
    assert.equal(loaded.exports.contactCorrectionSchema.safeParse({ reference: key, bookingKey: key, channel: "MOBILE", value: "nonsense" }).success, false);
    assert.equal(loaded.exports.contactCorrectionSchema.safeParse({ reference: key, bookingKey: key, channel: "EMAIL", value: "bad-email" }).success, false);
    const changed = await correct();
    assert.equal(changed.value, "+27820000000"); assert.equal(changed.delivered, true);
    assert.equal(sends[0].phone, changed.value);
    const saved = await db.reservation.findUniqueOrThrow({ where: { id: reservation.id } });
    assert.equal(saved.holdExpiresAt?.getTime(), hold.getTime());
    assert.equal(saved.verificationExpiresAt?.getTime(), hold.getTime());
    assert.equal(saved.verificationCodeHash, verificationHash(reservation.id, sends[0].code));
    assert.equal((await verifyPublicReservation(key, "111111")).ok, false);
    await db.reservation.update({ where: { id: reservation.id }, data: { contactVerifiedAt: new Date(), verificationAttempts: 2 } });
    await db.customer.update({ where: { id: customer.id }, data: { phoneVerifiedAt: new Date() } });
    assert.equal((await correct()).ok, false);
    await db.reservation.update({ where: { id: reservation.id }, data: { verificationCodeHash: emailVerificationHash(reservation.id, "222222") } });
    const email = await correct("EMAIL", "Correct@Example.invalid");
    assert.equal(email.value, "correct@example.invalid"); assert.equal(sends.at(-1)?.email, email.value);
    assert.equal((await verifyPublicReservationEmail(key, "222222")).ok, false);
    assert.ok((await db.customer.findUniqueOrThrow({ where: { id: customer.id } })).phoneVerifiedAt);
    delivered = false;
    const failed = await correct("EMAIL", "next@example.invalid");
    assert.equal(failed.ok, true); assert.equal(failed.delivered, false);
    assert.equal((await db.customer.findUniqueOrThrow({ where: { id: customer.id } })).email, "next@example.invalid");
    await db.customer.update({ where: { id: customer.id }, data: { emailVerifiedAt: new Date() } });
    assert.equal((await correct("EMAIL", "no@example.invalid")).ok, false);
    await db.customer.update({ where: { id: customer.id }, data: { emailVerifiedAt: null } });
    await db.reservation.update({ where: { id: reservation.id }, data: { verificationAttempts: 9 } });
    assert.equal((await correct("EMAIL", "no@example.invalid")).ok, false);
    await db.reservation.update({ where: { id: reservation.id }, data: { verificationAttempts: 2, holdExpiresAt: new Date(0) } });
    assert.equal((await correct("EMAIL", "no@example.invalid")).ok, false);
    await db.reservation.update({ where: { id: reservation.id }, data: { holdExpiresAt: hold, contactVerifiedAt: null } });
    await db.customer.update({ where: { id: customer.id }, data: { phoneVerifiedAt: null } });
    const before = sends.length;
    const races = await Promise.all([correct(), correct(), correct()]);
    assert.equal(races.filter(result => result.ok).length, 2);
    assert.equal(sends.length - before, 2);
    assert.equal((await db.reservation.findUniqueOrThrow({ where: { id: reservation.id } })).verificationAttempts, 4);
    assert.equal((await db.unit.findUniqueOrThrow({ where: { id: unit.id } })).status, "RESERVED");
    await db.reservation.update({ where: { id: reservation.id }, data: { verificationAttempts: 2 } });
    const shared = await db.reservation.create({ data: { facilityId: facility.id, customerId: customer.id, unitId: unit.id, quotedRate: 100, source: "PUBLIC_WEBSITE" } });
    assert.equal((await correct()).ok, false, "never change a shared customer");
    await db.reservation.delete({ where: { id: shared.id } });
    const lease = await db.publicReservationLease.create({ data: { reservationId: reservation.id, version: "fixture", paymentMethod: "CARD", content: "fixture", clauses: [], sha256: "a".repeat(64), signingToken: randomUUID(), expiresAt: hold } });
    assert.equal((await correct()).ok, false, "freeze contact details once a lease exists");
    await db.publicReservationLease.delete({ where: { id: lease.id } });
    await db.reservation.update({ where: { id: reservation.id }, data: { status: "CANCELLED" } });
    assert.equal((await correct()).ok, false);
    const audits = await db.auditEvent.findMany({ where: { entityId: reservation.id, action: "public_reservation.contact_corrected" } });
    assert.ok(audits.length > 0); assert.ok(audits.every(row => !JSON.stringify(row.after).includes("@") && !JSON.stringify(row.after).includes("+27")));
  } finally {
    await db.auditEvent.deleteMany({ where: { organisationId: org.id } });
    await db.reservation.deleteMany({ where: { facilityId: facility.id } });
    await db.customer.deleteMany({ where: { organisationId: org.id } });
    await db.unit.deleteMany({ where: { facilityId: facility.id } });
    await db.unitType.deleteMany({ where: { facilityId: facility.id } });
    await db.facility.delete({ where: { id: facility.id } });
    await db.organisation.delete({ where: { id: org.id } });
    await db.$disconnect();
  }
});
