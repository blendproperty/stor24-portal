import assert from "node:assert/strict";
import test from "node:test";
import { createHash, randomUUID } from "node:crypto";
import { Prisma } from "../../src/generated/prisma/client";
import { db } from "../../src/lib/db";
import { scheduledBillingGroupHash } from "../../src/lib/scheduled-billing-group";
import { runRecognitionWorkerInIsolatedTest, recognitionWorkerHealthInIsolatedTest, releaseRecognitionIssueInIsolatedTest } from "../../src/lib/scheduled-billing-worker";

test("monitored worker recovers missed groups, isolates failures and requires reviewed retry", async () => {
  assert.equal(process.env.NODE_ENV, "test"); assert.equal(process.env.MERCHANDISE_DB_TEST, "isolated-ci"); assert.equal(new URL(process.env.DATABASE_URL!).hostname, "localhost");
  const key = randomUUID();
  try {
    const org = await db.organisation.create({ data: { name: "Synthetic", slug: key } });
    const facility = await db.facility.create({ data: { organisationId: org.id, name: "Synthetic", code: key } });
    const user = await db.user.create({ data: { organisationId: org.id, name: "Synthetic", email: `${key}@example.invalid` } });
    const customer = await db.customer.create({ data: { organisationId: org.id, firstName: "Synthetic" } });
    const account = await db.account.create({ data: { customerId: customer.id, accountNumber: key } });
    const tenancy = await db.tenancy.create({ data: { facilityId: facility.id, customerId: customer.id, accountId: account.id, status: "ACTIVE", startDate: new Date("2025-01-01") } });
    const scope = { organisationId: org.id, userId: user.id, facilityIds: [facility.id], unrestrictedFacilities: false };
    const dueAt = new Date("2027-01-01T00:00:00+02:00");
    async function makeInvoice(index: number, effectiveAt: Date, broken = false) {
      const content = `synthetic-${index}`, sha256 = createHash("sha256").update(content).digest("hex");
      const invoice = await db.document.create({ data: { tenancyId: tenancy.id, type: "INVOICE", status: "GENERATED", storageKey: "synthetic", content: broken ? "altered" : content, sha256 } });
      const base = { accountId: account.id, organisationId: org.id, facilityId: facility.id, invoiceId: invoice.id, effectiveAt };
      const lines = [ { ...base, externalRef: `rent-${key}-${index}`, description: "Rent", lineType: "CHARGE", amount: new Prisma.Decimal("100.00"), taxAmount: new Prisma.Decimal("0.00") }, { ...base, externalRef: `credit-${key}-${index}`, description: "Synthetic credit", lineType: "CREDIT", amount: new Prisma.Decimal("10.00"), taxAmount: new Prisma.Decimal("0.00") } ];
      const groupHash = scheduledBillingGroupHash(lines);
      await db.scheduledBillingCharge.createMany({ data: lines.map(line => ({ ...line, groupSize: 2, groupHash })) });
      return { invoice, content };
    }
    const broken = await makeInvoice(0, new Date("2026-11-01T00:00:00+02:00"), true);
    for (let i = 1; i <= 27; i++) await makeInvoice(i, new Date("2026-12-01T00:00:00+02:00"));
    await makeInvoice(28, new Date("2027-02-01T00:00:00+02:00"));
    assert.equal((await recognitionWorkerHealthInIsolatedTest(org.id, dueAt)).status, "NEVER_RUN");
    await db.billingRecognitionLease.create({ data: { organisationId: org.id, token: "existing", expiresAt: new Date(Date.now() + 60_000) } });
    await assert.rejects(runRecognitionWorkerInIsolatedTest(org.id, dueAt), /ALREADY_RUNNING/);
    await db.billingRecognitionLease.update({ where: { organisationId: org.id }, data: { expiresAt: new Date(Date.now() - 1000) } });
    await db.billingRecognitionRun.create({ data: { organisationId: org.id, status: "RUNNING", startedAt: new Date(Date.now() - 30 * 60_000) } });
    assert.equal((await recognitionWorkerHealthInIsolatedTest(org.id, dueAt)).status, "STALE");
    const first = await runRecognitionWorkerInIsolatedTest(org.id, dueAt);
    assert.equal(first.processed, 24); assert.equal(first.held, 1);
    const second = await runRecognitionWorkerInIsolatedTest(org.id, dueAt);
    assert.equal(second.processed, 3); assert.equal(second.held, 0);
    const third = await runRecognitionWorkerInIsolatedTest(org.id, dueAt);
    assert.equal(third.processed, 0); assert.equal(third.held, 0);
    const health = await recognitionWorkerHealthInIsolatedTest(org.id, dueAt);
    assert.equal(health.status, "REVIEW_REQUIRED"); assert.equal(health.overdue, 1); assert.equal(health.held, 1);
    assert.equal((await db.account.findUniqueOrThrow({ where: { id: account.id } })).balance.toFixed(2), "2430.00");
    const issue = await db.billingRecognitionIssue.findFirstOrThrow({ where: { organisationId: org.id, status: "HELD" } });
    assert.equal(issue.code, "BILLING_RECOGNITION_GROUP_REVIEW");
    await assert.rejects(releaseRecognitionIssueInIsolatedTest({ ...scope, facilityIds: [] }, issue.id, issue.code, issue.updatedAt), /ISSUE_CHANGED/);
    await assert.rejects(releaseRecognitionIssueInIsolatedTest(scope, issue.id, "BILLING_WRONG", issue.updatedAt), /ISSUE_CHANGED/);
    await assert.rejects(releaseRecognitionIssueInIsolatedTest(scope, issue.id, issue.code, new Date(issue.updatedAt.getTime() - 1)), /ISSUE_CHANGED/);
    await db.document.update({ where: { id: broken.invoice.id }, data: { content: broken.content } });
    await releaseRecognitionIssueInIsolatedTest(scope, issue.id, issue.code, issue.updatedAt);
    await assert.rejects(releaseRecognitionIssueInIsolatedTest(scope, issue.id, issue.code, issue.updatedAt), /ISSUE_CHANGED/);
    assert.equal((await runRecognitionWorkerInIsolatedTest(org.id, dueAt)).processed, 1);
    assert.equal((await db.account.findUniqueOrThrow({ where: { id: account.id } })).balance.toFixed(2), "2520.00");
    assert.equal((await recognitionWorkerHealthInIsolatedTest(org.id, dueAt)).status, "HEALTHY");
    assert.equal(await db.ledgerEntry.count({ where: { accountId: account.id } }), 56);
    assert.equal(await db.auditEvent.count({ where: { organisationId: org.id, action: "billing.recognition_issue_released" } }), 1);
    assert.equal(await db.scheduledBillingCharge.count({ where: { organisationId: org.id, recognisedAt: null } }), 2);
    const stale = await recognitionWorkerHealthInIsolatedTest(org.id, dueAt, new Date(Date.now() + 16 * 60_000));
    assert.equal(stale.status, "STALE");
    const nextDue = new Date("2027-02-01T00:00:00+02:00");
    const overlapping = await Promise.allSettled([runRecognitionWorkerInIsolatedTest(org.id, nextDue), runRecognitionWorkerInIsolatedTest(org.id, nextDue)]);
    const completed = overlapping.filter(result => result.status === "fulfilled");
    assert.ok(completed.length >= 1);
    assert.equal(completed.reduce((sum, result) => sum + (result.status === "fulfilled" ? result.value.processed : 0), 0), 1);
    assert.equal((await db.account.findUniqueOrThrow({ where: { id: account.id } })).balance.toFixed(2), "2610.00");
    assert.equal(await db.ledgerEntry.count({ where: { accountId: account.id } }), 58);
    await db.scheduledBillingCharge.create({ data: { accountId: account.id, organisationId: org.id, facilityId: facility.id, externalRef: `unlinked-${key}`, description: "Synthetic orphan", amount: "10", taxAmount: "0", effectiveAt: dueAt } });
    assert.equal((await runRecognitionWorkerInIsolatedTest(org.id, nextDue)).processed, 0);
    const orphanHealth = await recognitionWorkerHealthInIsolatedTest(org.id, nextDue);
    assert.equal(orphanHealth.status, "REVIEW_REQUIRED"); assert.equal(orphanHealth.unlinked, 1);
    const staleOrphanHealth = await recognitionWorkerHealthInIsolatedTest(org.id, nextDue, new Date(Date.now() + 16 * 60_000));
    assert.equal(staleOrphanHealth.status, "REVIEW_REQUIRED"); assert.equal(staleOrphanHealth.stale, true);
    assert.equal((await db.account.findUniqueOrThrow({ where: { id: account.id } })).balance.toFixed(2), "2610.00");
    delete process.env.MERCHANDISE_DB_TEST;
    await assert.rejects(runRecognitionWorkerInIsolatedTest(org.id, dueAt), /ISOLATED_TEST_ONLY/);
    process.env.MERCHANDISE_DB_TEST = "isolated-ci";
  } finally { await db.$disconnect(); }
});
